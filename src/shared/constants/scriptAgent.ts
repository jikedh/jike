- 未完成的危险动作；
- 身份刚被识破或即将暴露；
- 关键证据改变所有人的判断；
- 关系即将发生不可逆变化；
- 更高层对手出现；
- 主角必须立即作出困难选择；
- 观众知道危险已经发生，而角色尚未知情；
- 主角以为问题解决，却发现更大的代价。

卡点必须写出具体画面、动作、台词或问题，不以“未完待续”“众人震惊”代替。

